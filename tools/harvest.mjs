#!/usr/bin/env node
// The harvest, out of the page (ADR 0011, P17, P23): reads copied harvest records or raw journals and writes the merged report.
//
//   node tools/harvest.mjs <files or folders…> [--out harvest/<name>.md] [--strip] [--json]
//   node tools/story.mjs harvest <files or folders…> …        (the same, from the creator kit)
//
// Inputs, by content: a harvest record or an array of them (.json, as « Harvest » → « Copy all » gives them, or an export of
// the artifact's `harvest` collection: an array of documents, or { docs: [...] }); a core journal (.jsonl, « Copy journal »);
// a legacy free-mode journal (the French text that starts with "JOURNAL · ", any extension). Folders are read one level deep.
// Prints the report and writes it as Markdown (default harvest/<date>-report.md). Nothing is applied: the proposals at the
// end are for a person to accept or drop, layer by layer (P23).
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { harvestRecord, mergeRecords, isLegacyText } from '../core/harvest.js';
import { fromJSONL } from '../core/journal.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/* One file's text → the records it holds (records copied from the page, or journals made into records). */
export function readInput(text, { name = 'input', strip = false } = {}) {
  const t = String(text);
  if (isLegacyText(t)) return [harvestRecord(t, { strip })];
  const s = t.trim();
  if (s.startsWith('[') || (s.startsWith('{') && !s.includes('\n{'))) {
    let j; try { j = JSON.parse(s); } catch (_) { j = null; }
    if (j) {
      const list = Array.isArray(j) ? j : Array.isArray(j.docs) ? j.docs.map(d => d.data || d) : Array.isArray(j.records) ? j.records : [j];
      return list.filter(r => r && r.type === 'harvest').map(r => strip && !r.stripped && r.journal && r.journal.text ? harvestRecord(r.journal.format === 'legacy-text' ? r.journal.text : fromJSONL(r.journal.text), { strip, meta: metaOf(r) }) : r);
    }
  }
  if (s.startsWith('{')) return [harvestRecord(fromJSONL(s), { strip, meta: { id: name } })];
  return [];
}
const metaOf = r => ({ id: r.id, mode: r.mode, device: r.device, lang: r.lang, pack: r.pack, versions: r.versions });

export function readPaths(paths, opts = {}) {
  const files = [];
  for (const p of paths) {
    const st = statSync(p);
    if (st.isDirectory()) for (const f of readdirSync(p).sort()) { const q = join(p, f); if (statSync(q).isFile() && !/\.md$/.test(f)) files.push(q); }
    else files.push(p);
  }
  return files.flatMap(f => readInput(readFileSync(f, 'utf8'), Object.assign({ name: f.split('/').pop().replace(/\.[^.]*$/, '') }, opts)).map(r => Object.assign(r, { _file: f })));
}

const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const LAYERS = [
  ['engine', '1. Engine and vocabulary: things and sounds asked for and missing', "the engine's owner", 'Drafts for `src/modeles.json` or `src/bruitages.json` when the shape or synth vocabulary could make it, else a line for the engine\'s vocabulary wishlist.'],
  ['story', '2. Story: people, names, facts, places a model improvised', "the story's author", 'PDL source lines for the story\'s pack (`facts/*.pdl`, a character sheet), with the session as their source.'],
  ['character', '3. Characters: ways of speaking or reacting', "the story's author", 'A tendency, an example (`>`) or a counter-example (`x`) for a character sheet; open questions (`?`) where she was refused.'],
  ['framework', '4. Framework: unsure judgements, slow calls', "the engine's owner", 'A prepared option, a compiled rule, a threshold or a budget.'],
];

export function renderReport(m, { title = 'Harvest report', inputs = [] } = {}) {
  const L = [`# ${title}`, '', `Generated by \`node tools/harvest.mjs\` from ${m.records.length} record(s)${inputs.length ? ': ' + inputs.map(f => '`' + f + '`').join(', ') : ''}. Nothing below is applied: each proposal is accepted or dropped by the person named (P23, ADR 0011 §3).`, ''];
  L.push('## Sessions', '', '| record | mode | source | pack | device | model | turns | duration | versions |', '|---|---|---|---|---|---|---|---|---|');
  for (const r of m.records) L.push(`| ${cell(r.id)} | ${r.mode} | ${r.source}${r.stripped ? ' (stripped)' : ''} | ${cell(r.pack)} | ${cell(r.device)} | ${r.with_model ? 'yes' : 'no'} | ${r.turns} | ${r.duration_s} s | ${cell(Object.entries(r.versions || {}).map(([k, v]) => k + ' ' + (typeof v === 'object' ? JSON.stringify(v) : v)).join(', '))} |`);
  L.push('', '## Asked and not doable, grouped by what was missing', '');
  if (!m.requests.length) L.push('Nothing in these journals.');
  else { L.push('| missing | times | kinds | what the player said | from |', '|---|---|---|---|---|'); for (const g of m.requests) L.push(`| ${cell(g.missing)} | ${g.n} | ${cell(g.kinds.join(', '))} | ${cell(g.examples.map(e => '« ' + e + ' »').join(' · '))} | ${cell(g.from.join(', '))} |`); }
  L.push('', '## Improvised', '');
  if (!m.improvised.length) L.push('Nothing improvised in these journals.');
  for (const i of m.improvised) L.push(`- ${i.record} #${i.seq} ${i.kind}: ${i.text}${i.said ? ' — after « ' + i.said + ' »' : ''}${i.by ? ' (' + i.by + ')' : ''}`);
  L.push('', '## Latency by adapter, instrument and purpose', '');
  const lat = Object.entries(m.latency);
  if (!lat.length) L.push('No timed model call.');
  else { L.push('| call | n | p50 ms | p95 ms | budget ms | over budget | sessions |', '|---|---|---|---|---|---|---|'); for (const [k, r] of lat) L.push(`| ${cell(k)} | ${r.n} | ${r.p50 ?? ''} | ${r.p95 ?? ''} | ${r.budget ?? ''} | ${r.over ?? ''} | ${r.sessions} |`); }
  L.push('', '## Proposals', '', 'One section per layer. Tick to accept; an accepted proposal enters as data with its provenance, in a commit by the person who decides.', '');
  for (const [k, head, owner, what] of LAYERS) {
    const ps = m.proposals[k];
    L.push(`### ${head}`, '', `Decides: ${owner}. ${what}`, '');
    if (!ps.length) { L.push('None from these records.', ''); continue; }
    for (const p of ps) {
      L.push(`- [ ] **${p.title}** — seen ${p.seen}× in ${p.sessions.length} session(s); from ${p.from.map(f => f.record + ' #' + f.seq).join(', ')}; decides: ${p.owner}${p.target ? '; goes to `' + p.target + '`' : ''}`);
      L.push('', '  ```' + (p.kind === 'model' || p.kind === 'sound' ? 'json' : ''), ...p.text.split('\n').map(l => '  ' + l), '  ```', '');
    }
  }
  return L.join('\n') + '\n';
}

export function main(argv, { print = console.log } = {}) {
  const args = argv.slice(), opt = n => { const i = args.indexOf(n); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; }, flag = n => { const i = args.indexOf(n); if (i < 0) return false; args.splice(i, 1); return true; };
  const out = opt('--out'), title = opt('--title'), strip = flag('--strip'), json = flag('--json');
  if (!args.length) { print('usage: node tools/harvest.mjs <files or folders…> [--out harvest/<name>.md] [--title t] [--strip] [--json]'); return 2; }
  const recs = readPaths(args, { strip });
  if (!recs.length) { print('no harvest record nor journal found in ' + args.join(' ')); return 1; }
  const m = mergeRecords(recs);
  const md = renderReport(m, { title: title || 'Harvest report', inputs: [...new Set(recs.map(r => relative(process.cwd(), r._file)))] });
  const target = out || join(ROOT, 'harvest', new Date().toISOString().slice(0, 10) + '-report.md');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, md);
  print(json ? JSON.stringify(m, null, 2) : md + `\nwritten: ${relative(process.cwd(), target)}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
